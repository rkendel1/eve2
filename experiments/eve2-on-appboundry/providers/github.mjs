// GitHub as a provider of two neutral contract families:
//   tracker.items.*   issues: get, find, create, comment
//   code.workspace.*  a working copy: open, status, list, read, search, write, run (declared checks only), result, diff
//   code.changes.*    publish a working copy's changes as a branch and pull request; read a pull request back
//
// GitHub access is this provider's. Here the environment's proxy authenticates api.github.com and github.com (run with
// NODE_USE_ENV_PROXY=1 so fetch uses it); elsewhere EVE_GITHUB_TOKEN is read. An ambient GITHUB_TOKEN is never used. Bounds are the provider's, whatever the consumer asks: an allowlist of repositories, branches
// under eve/, no merge capability at all, no workflow files, and only the checks declared per repository.
import { spawn } from "node:child_process";
import { createHash, randomUUID } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync, statSync, readdirSync, rmSync } from "node:fs";
import { join, normalize, relative, isAbsolute } from "node:path";
import { tmpdir } from "node:os";
import { defineCapability } from "@appport/core";
import { AppPortError } from "@appport/protocol";
import { s } from "@appport/schema";
import { log, serve } from "./serve.mjs";

const ALLOWED = (process.env.GITHUB_REPOSITORIES ?? "rkendel1/appboundry").split(",").map((r) => r.trim()).filter(Boolean);
const WORK = process.env.GITHUB_WORKDIR ?? join(tmpdir(), "eve-workspaces");
const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
const NOISE_ENV = ["FELTDB_URL", "FELTDB_APPLICATION_ID", "FELTDB_ENVIRONMENT", "FELTDB_MODE", "FELTDB_NAMESPACE", "FELTDB_TOKEN"];
/** The checks a consumer may run, per repository: name → argv (target appended where allowed). */
const CHECKS = {
  "rkendel1/appboundry": {
    prepare: { argv: ["sh", "-c", "pnpm install --frozen-lockfile && pnpm build"], timeoutMs: 900_000 },
    build: { argv: ["pnpm", "build"], timeoutMs: 600_000 },
    test: { argv: ["npx", "vitest", "run"], target: "path", timeoutMs: 600_000 },
  },
};
const faults = { failNextPublish: false };

function repository(name) {
  if (!ALLOWED.includes(name)) throw new AppPortError("FORBIDDEN", `This provider does not work on ${name}; it serves ${ALLOWED.join(", ")}.`);
  return name;
}

async function gh(method, path, body) {
  const headers = { accept: "application/vnd.github+json", "x-github-api-version": "2022-11-28", "user-agent": "eve2-github-provider" };
  if (process.env.EVE_GITHUB_TOKEN) headers.authorization = `Bearer ${process.env.EVE_GITHUB_TOKEN}`;
  if (body) headers["content-type"] = "application/json";
  const response = await fetch(`https://api.github.com${path}`, { method, headers, ...(body ? { body: JSON.stringify(body) } : {}) });
  const json = response.status === 204 ? null : await response.json().catch(() => null);
  if (!response.ok) {
    log("github.error", { method, path, status: response.status, message: json?.message });
    const code = response.status === 404 ? "NOT_FOUND" : response.status === 401 || response.status === 403 ? "FORBIDDEN" : response.status === 409 || response.status === 422 ? "CONFLICT" : response.status === 429 ? "RATE_LIMITED" : "UNAVAILABLE";
    throw new AppPortError(code, `GitHub ${method} ${path.split("?")[0]}: ${json?.message ?? response.status}`);
  }
  log("github.call", { method, path: path.split("?")[0], status: response.status });
  return json;
}

/* ------------------------------------------------------------------ tracker.items.* */

const item = (i) => ({ number: i.number, title: i.title, state: i.state, url: i.html_url, author: i.user?.login, labels: (i.labels ?? []).map((l) => l.name ?? l), body: i.body ?? "" });
const tracker = [
  defineCapability({
    name: "tracker.items.get", version: 1, description: "Read an issue with its comments.",
    input: s.object({ repository: s.string(), number: s.number() }), output: s.unknown(), authorization: [],
    handler: async ({ repository: r, number }) => {
      const issue = await gh("GET", `/repos/${repository(r)}/issues/${number}`);
      const comments = await gh("GET", `/repos/${r}/issues/${number}/comments?per_page=100`);
      return { ...item(issue), comments: comments.map((c) => ({ author: c.user?.login, body: c.body, at: c.created_at })) };
    },
  }),
  defineCapability({
    name: "tracker.items.find", version: 1, description: "Find issues (open or closed) whose title contains the given words.",
    input: s.object({ repository: s.string(), query: s.string() }), output: s.unknown(), authorization: [],
    handler: async ({ repository: r, query }) => {
      const issues = await gh("GET", `/repos/${repository(r)}/issues?state=all&per_page=100`);
      const words = query.toLowerCase().split(/\W+/).filter((w) => w.length > 3);
      const scored = issues.filter((i) => !i.pull_request).map((i) => ({ i, hits: words.filter((w) => i.title.toLowerCase().includes(w)).length }));
      return { matches: scored.filter((x) => words.length && x.hits / words.length >= 0.6).map((x) => item(x.i)) };
    },
  }),
  defineCapability({
    name: "tracker.items.create", version: 1, description: "Open an issue.",
    input: s.object({ repository: s.string(), title: s.string(), body: s.string(), labels: s.optional(s.array(s.string())) }), output: s.unknown(), authorization: [], idempotency: "supported",
    handler: async ({ repository: r, title, body, labels }) => item(await gh("POST", `/repos/${repository(r)}/issues`, { title, body: body + FOOTER, ...(labels?.length ? { labels } : {}) })),
  }),
  defineCapability({
    name: "tracker.items.comment", version: 1, description: "Comment on an issue.",
    input: s.object({ repository: s.string(), number: s.number(), body: s.string() }), output: s.unknown(), authorization: [], idempotency: "supported",
    handler: async ({ repository: r, number, body }) => { const c = await gh("POST", `/repos/${repository(r)}/issues/${number}/comments`, { body: body + FOOTER }); return { id: String(c.id), url: c.html_url }; },
  }),
];

/* ------------------------------------------------------------------ code.workspace.* */

const workspaces = new Map();
const runs = new Map();
mkdirSync(WORK, { recursive: true });

function exec(argv, cwd, timeoutMs) {
  return new Promise((resolve) => {
    const env = { ...process.env, CI: "1" };
    for (const k of NOISE_ENV) delete env[k];
    const child = spawn(argv[0], argv.slice(1), { cwd, env, stdio: ["ignore", "pipe", "pipe"] });
    let out = "";
    const keep = (d) => { out += d; if (out.length > 400_000) out = out.slice(-200_000); };
    child.stdout.on("data", keep); child.stderr.on("data", keep);
    const started = Date.now();
    const timer = setTimeout(() => child.kill("SIGKILL"), timeoutMs);
    child.on("close", (code, signal) => { clearTimeout(timer); resolve({ exitCode: code ?? -1, signal, durationMs: Date.now() - started, output: out }); });
  });
}
function workspace(id) {
  const w = workspaces.get(id);
  if (!w) throw new AppPortError("NOT_FOUND", `No workspace ${id} (workspaces live as long as this provider process).`);
  return w;
}
function inside(w, path) {
  const p = normalize(path ?? ".").replace(/^\/+/, "");
  if (isAbsolute(p) || p.startsWith("..") || p === ".git" || p.startsWith(".git/")) throw new AppPortError("INVALID_INPUT", `Path ${path} is outside the working copy.`);
  return { rel: p, abs: join(w.dir, p) };
}
function startRun(w, check, target) {
  const spec = CHECKS[w.repository]?.[check];
  if (!spec) throw new AppPortError("INVALID_INPUT", `Unknown check ${check}; declared: ${Object.keys(CHECKS[w.repository] ?? {}).join(", ")}.`);
  const argv = [...spec.argv];
  if (spec.target) { if (!target) throw new AppPortError("INVALID_INPUT", `${check} needs a target path.`); argv.push(inside(w, target).rel); }
  const id = `run_${randomUUID().slice(0, 8)}`;
  const run = { id, workspace: w.id, check, target: target ?? null, state: "running", startedAt: new Date().toISOString() };
  runs.set(id, run);
  run.promise = exec(argv, w.dir, spec.timeoutMs).then((r) => {
    Object.assign(run, { state: "finished", exitCode: r.exitCode, signal: r.signal, durationMs: r.durationMs, output: r.output.slice(-6000) });
    log("check.finished", { id, check, target, exitCode: r.exitCode, durationMs: r.durationMs });
  });
  return run;
}
const runView = ({ promise, ...r }) => r;
async function settle(run, waitMs) { await Promise.race([run.promise, new Promise((r) => setTimeout(r, waitMs))]); return runView(run); }

const code = [
  defineCapability({
    name: "code.workspace.open", version: 1, description: "Open a working copy of a repository at a ref, and prepare it (install and build). Returns while preparation may still run.",
    input: s.object({ repository: s.string(), ref: s.optional(s.string()) }), output: s.unknown(), authorization: [], idempotency: "supported",
    handler: async ({ repository: r, ref }, context) => {
      repository(r);
      const key = createHash("sha256").update(context.idempotencyKey ?? randomUUID()).digest("hex").slice(0, 12);
      const existing = [...workspaces.values()].find((w) => w.key === key);
      if (existing) return { workspace: existing.id, repository: r, sha: existing.sha, prepare: runView(runs.get(existing.prepare)) };
      const id = `ws_${key}`;
      const dir = join(WORK, id);
      rmSync(dir, { recursive: true, force: true });
      const clone = await exec(["git", "clone", "--depth", "20", ...(ref ? ["--branch", ref] : []), `https://github.com/${r}.git`, dir], WORK, 300_000);
      if (clone.exitCode !== 0) throw new AppPortError("UNAVAILABLE", `Clone failed: ${clone.output.slice(-400)}`);
      const sha = (await exec(["git", "rev-parse", "HEAD"], dir, 10_000)).output.trim();
      const base = ref ?? (await exec(["git", "rev-parse", "--abbrev-ref", "HEAD"], dir, 10_000)).output.trim();
      const w = { id, key, repository: r, dir, sha, base };
      workspaces.set(id, w);
      w.prepare = startRun(w, "prepare").id;
      log("workspace.opened", { id, repository: r, sha, base });
      return { workspace: id, repository: r, base, sha, checks: Object.keys(CHECKS[r] ?? {}), prepare: await settle(runs.get(w.prepare), 20_000) };
    },
  }),
  defineCapability({
    name: "code.workspace.list", version: 1, description: "List a directory of the working copy.",
    input: s.object({ workspace: s.string(), path: s.optional(s.string()) }), output: s.unknown(), authorization: [],
    handler: async ({ workspace: id, path }) => {
      const w = workspace(id); const { rel, abs } = inside(w, path);
      if (!existsSync(abs) || !statSync(abs).isDirectory()) throw new AppPortError("NOT_FOUND", `${rel} is not a directory.`);
      return { path: rel, entries: readdirSync(abs, { withFileTypes: true }).filter((e) => e.name !== ".git" && e.name !== "node_modules" && e.name !== "dist").map((e) => `${e.name}${e.isDirectory() ? "/" : ""}`).sort() };
    },
  }),
  defineCapability({
    name: "code.workspace.read", version: 1, description: "Read a file (or a range of lines) of the working copy, with line numbers.",
    input: s.object({ workspace: s.string(), path: s.string(), startLine: s.optional(s.number()), endLine: s.optional(s.number()) }), output: s.unknown(), authorization: [],
    handler: async ({ workspace: id, path, startLine, endLine }) => {
      const w = workspace(id); const { rel, abs } = inside(w, path);
      if (!existsSync(abs) || !statSync(abs).isFile()) throw new AppPortError("NOT_FOUND", `${rel} is not a file.`);
      const lines = readFileSync(abs, "utf8").split("\n");
      const from = Math.max(1, startLine ?? 1), to = Math.min(lines.length, endLine ?? Math.min(lines.length, from + 299));
      return { path: rel, sha: w.sha, startLine: from, endLine: to, totalLines: lines.length, content: lines.slice(from - 1, to).map((l, i) => `${from + i}\t${l}`).join("\n") };
    },
  }),
  defineCapability({
    name: "code.workspace.search", version: 1, description: "Search the working copy for a regular expression (git grep).",
    input: s.object({ workspace: s.string(), pattern: s.string(), path: s.optional(s.string()) }), output: s.unknown(), authorization: [],
    handler: async ({ workspace: id, pattern, path }) => {
      const w = workspace(id);
      const r = await exec(["git", "grep", "-n", "-I", "-E", "--max-count", "20", pattern, "--", ...(path ? [inside(w, path).rel] : [])], w.dir, 30_000);
      const matches = r.output.split("\n").filter(Boolean).slice(0, 120).map((l) => { const m = /^([^:]+):(\d+):(.*)$/.exec(l); return m ? { path: m[1], line: Number(m[2]), text: m[3].slice(0, 240) } : null; }).filter(Boolean);
      return { pattern, matches, truncated: r.output.split("\n").length > 120 };
    },
  }),
  defineCapability({
    name: "code.workspace.write", version: 1, description: "Write a file of the working copy (whole content). Workflow files are refused.",
    input: s.object({ workspace: s.string(), path: s.string(), content: s.string() }), output: s.unknown(), authorization: [], idempotency: "supported",
    handler: async ({ workspace: id, path, content }) => {
      const w = workspace(id); const { rel, abs } = inside(w, path);
      if (rel.startsWith(".github/")) throw new AppPortError("FORBIDDEN", "Workflow and repository settings files are not written by this provider.");
      mkdirSync(join(abs, ".."), { recursive: true });
      writeFileSync(abs, content);
      return { path: rel, bytes: Buffer.byteLength(content) };
    },
  }),
  defineCapability({
    name: "code.workspace.run", version: 1, description: "Start a declared check (prepare, build, or test <path>). Answers when it finishes or after 20 s with its run id.",
    input: s.object({ workspace: s.string(), check: s.string(), target: s.optional(s.string()) }), output: s.unknown(), authorization: [], idempotency: "supported",
    handler: async ({ workspace: id, check, target }) => settle(startRun(workspace(id), check, target), 20_000),
  }),
  defineCapability({
    name: "code.workspace.result", version: 1, description: "The state of a check run, and its output once finished.",
    input: s.object({ run: s.string() }), output: s.unknown(), authorization: [],
    handler: async ({ run }) => { const r = runs.get(run); if (!r) throw new AppPortError("NOT_FOUND", `No run ${run}.`); return settle(r, 15_000); },
  }),
  defineCapability({
    name: "code.workspace.diff", version: 1, description: "What changed in the working copy since it was opened.",
    input: s.object({ workspace: s.string() }), output: s.unknown(), authorization: [],
    handler: async ({ workspace: id }) => {
      const w = workspace(id);
      await exec(["git", "add", "-A", "--", ".", ":!node_modules"], w.dir, 30_000);
      const stat = (await exec(["git", "diff", "--cached", "--numstat"], w.dir, 30_000)).output.split("\n").filter(Boolean).map((l) => { const [a, d, p] = l.split("\t"); return { path: p, additions: Number(a), deletions: Number(d) }; });
      const patch = (await exec(["git", "diff", "--cached"], w.dir, 30_000)).output;
      return { base: w.sha, files: stat, patch: patch.slice(0, 20_000), patchTruncated: patch.length > 20_000, patchSha256: createHash("sha256").update(patch).digest("hex") };
    },
  }),
];

/* ------------------------------------------------------------------ code.changes.* */

const changes = [
  defineCapability({
    name: "code.changes.publish", version: 1, description: "Commit the working copy's changes on a new eve/ branch and open a pull request. Never merges.",
    input: s.object({ workspace: s.string(), branch: s.string(), title: s.string(), body: s.string(), message: s.string() }), output: s.unknown(), authorization: [], idempotency: "required",
    handler: async ({ workspace: id, branch, title, body, message }) => {
      const w = workspace(id);
      if (!/^eve\/[a-z0-9._/-]{1,80}$/.test(branch)) throw new AppPortError("INVALID_INPUT", "Branches are eve/<lowercase name>.");
      if (faults.failNextPublish) { faults.failNextPublish = false; throw new AppPortError("UNAVAILABLE", "Injected: publish failed before reaching GitHub."); }
      const open = await gh("GET", `/repos/${w.repository}/pulls?state=all&head=${w.repository.split("/")[0]}:${encodeURIComponent(branch)}`);
      if (open.length) return pr(open[0]);
      await exec(["git", "add", "-A", "--", ".", ":!node_modules"], w.dir, 30_000);
      const files = (await exec(["git", "diff", "--cached", "--name-status"], w.dir, 30_000)).output.split("\n").filter(Boolean).map((l) => l.split("\t"));
      if (!files.length) throw new AppPortError("INVALID_INPUT", "Nothing changed in the working copy.");
      const base = await gh("GET", `/repos/${w.repository}/git/commits/${w.sha}`);
      const tree = [];
      for (const [status, path] of files) {
        if (status.startsWith("D")) { tree.push({ path, mode: "100644", type: "blob", sha: null }); continue; }
        const blob = await gh("POST", `/repos/${w.repository}/git/blobs`, { content: readFileSync(join(w.dir, path)).toString("base64"), encoding: "base64" });
        tree.push({ path, mode: "100644", type: "blob", sha: blob.sha });
      }
      const newTree = await gh("POST", `/repos/${w.repository}/git/trees`, { base_tree: base.tree.sha, tree });
      const commit = await gh("POST", `/repos/${w.repository}/git/commits`, { message, tree: newTree.sha, parents: [w.sha] });
      await gh("POST", `/repos/${w.repository}/git/refs`, { ref: `refs/heads/${branch}`, sha: commit.sha });
      const created = await gh("POST", `/repos/${w.repository}/pulls`, { title, body: body + FOOTER, head: branch, base: w.base, draft: false });
      log("changes.published", { number: created.number, branch, commit: commit.sha });
      return pr(created);
    },
  }),
  defineCapability({
    name: "code.changes.get", version: 1, description: "Read a pull request back: state, head commit, files, and check runs on the head commit.",
    input: s.object({ repository: s.string(), number: s.number() }), output: s.unknown(), authorization: [],
    handler: async ({ repository: r, number }) => {
      const p = await gh("GET", `/repos/${repository(r)}/pulls/${number}`);
      const files = await gh("GET", `/repos/${r}/pulls/${number}/files?per_page=100`);
      const checks = await gh("GET", `/repos/${r}/commits/${p.head.sha}/check-runs?per_page=100`);
      return { ...pr(p), files: files.map((f) => ({ path: f.filename, status: f.status, additions: f.additions, deletions: f.deletions })), checks: checks.check_runs.map((c) => ({ name: c.name, status: c.status, conclusion: c.conclusion })) };
    },
  }),
];
const pr = (p) => ({ number: p.number, url: p.html_url, state: p.state, merged: Boolean(p.merged_at ?? p.merged), draft: p.draft, branch: p.head.ref, headSha: p.head.sha, base: p.base.ref });

serve({
  id: "github", name: "GitHub", capabilities: [...tracker, ...code, ...changes], port: Number(process.env.PORT ?? 5440), consumerToken: process.env.CONSUMER_TOKEN,
  control: async (req, res) => { let b = ""; for await (const c of req) b += c; Object.assign(faults, JSON.parse(b || "{}")); log("fault.set", faults); res.writeHead(204).end(); },
});
gh("GET", "/user").then((u) => log("github.identity", { login: u.login, repositories: ALLOWED }), (e) => log("github.unavailable", { message: e.message }));
